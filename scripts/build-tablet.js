'use strict';
/**
 * Build the tablet app: a self-contained web app that runs entirely in the
 * tablet's browser, with all data stored on the tablet (IndexedDB). No server.
 *
 *   node scripts/build-tablet.js        writes tablet/
 *
 * The output is plain static files: host the tablet/ folder on any HTTPS
 * static host (GitHub Pages, Netlify, Cloudflare Pages…), open it on the
 * tablet once, and add it to the home screen. After that it works offline.
 *
 * How: the same lib/*.js that power the server are bundled into
 * tablet/engine.js with a tiny CommonJS shim, so the tablet runs the exact
 * same logic (parser, reports, job matching, PM) as the server.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'tablet');
const LIB = ['store', 'parser', 'analytics', 'reports', 'pm', 'api'];
const PUBLIC_FILES = ['app.js', 'core.js', 'today.js', 'orders.js', 'parts.js', 'reports.js', 'schedule.js',
  'dashboard.js', 'team.js', 'logform.js', 'voice.js', 'style.css', 'icon.svg'];

function bundleEngine() {
  const mods = LIB.map((name) => {
    const src = fs.readFileSync(path.join(ROOT, 'lib', name + '.js'), 'utf8');
    return `  './${name}': function (module, exports, require) {\n${src}\n  },`;
  }).join('\n');
  const glue = fs.readFileSync(path.join(ROOT, 'public', 'local', 'engine-glue.js'), 'utf8');
  return `/* GENERATED by scripts/build-tablet.js from lib/*.js — do not edit by hand. */
const process = { env: {} };
const __dirname = '';
// Safari before iPadOS 15.4 has no structuredClone; our data is plain JSON.
const structuredClone = globalThis.structuredClone || ((v) => JSON.parse(JSON.stringify(v)));
const __modules = {
${mods}
};
const __cache = {};
function require(name) {
  const key = name.replace(/\\.js$/, '').replace(/^\\.\\.?\\/lib\\//, './');
  if (__cache[key]) return __cache[key].exports;
  if (!__modules[key]) throw new Error('Not available on the tablet: ' + name);
  const module = { exports: {} };
  __cache[key] = module;
  __modules[key](module, module.exports, require);
  return module.exports;
}
${glue}
`;
}

function build() {
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });

  const files = {};
  for (const f of PUBLIC_FILES) files[f] = fs.readFileSync(path.join(ROOT, 'public', f));
  files['engine.js'] = Buffer.from(bundleEngine());
  files['boot-local.js'] = fs.readFileSync(path.join(ROOT, 'public', 'local', 'boot-local.js'));

  // index.html: same page, but boots the local engine instead of a server.
  let html = fs.readFileSync(path.join(ROOT, 'public', 'index.html'), 'utf8');
  html = html.replace('<script type="module" src="app.js"></script>', '<script type="module" src="boot-local.js"></script>');
  html = html.replace('<title>Maintenance Tracker</title>', '<title>Maintenance Log</title>');
  files['index.html'] = Buffer.from(html);

  const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'public', 'manifest.webmanifest'), 'utf8'));
  manifest.name = 'Maintenance Log';
  manifest.start_url = './#today';
  manifest.scope = './';
  files['manifest.webmanifest'] = Buffer.from(JSON.stringify(manifest, null, 2) + '\n');

  // Service worker: caches every file so the app opens with no connection.
  // The version changes whenever any file changes, which makes tablets pick
  // up the new version the next time they're online.
  const hash = crypto.createHash('sha256');
  for (const name of Object.keys(files).sort()) hash.update(name).update(files[name]);
  const version = hash.digest('hex').slice(0, 12);
  const sw = fs.readFileSync(path.join(ROOT, 'public', 'local', 'sw.js'), 'utf8')
    .replace('__VERSION__', version)
    .replace('__FILES__', JSON.stringify(['./', ...Object.keys(files).sort()]));
  files['sw.js'] = Buffer.from(sw);
  files['.nojekyll'] = Buffer.from('');

  for (const [name, data] of Object.entries(files)) fs.writeFileSync(path.join(OUT, name), data);
  return { version, files: Object.keys(files) };
}

if (require.main === module) {
  const { version, files } = build();
  console.log(`Tablet app built in tablet/ (${files.length} files, version ${version}).`);
}

module.exports = { build, OUT };
